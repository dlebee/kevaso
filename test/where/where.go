// Package where works out, from the test code itself, which tests exist under each build tag and
// where each of them can run (CI, Lima, real cloud machines, bare metal). test/WHERE.md is its
// output, and where_test.go fails when that file is stale: regenerate it with `make where`.
package where

import (
	"bufio"
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"io/fs"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

// CIExpectedFile lists the tagged tests the CI e2e job must see pass (hack/skipbudget).
const CIExpectedFile = "test/e2e/ci-expected.txt"

type test struct {
	name, file, tag, where string
	inCI                   bool
}

// Generate returns the document for the tree at root.
func Generate(root string) (string, error) {
	ci, err := readList(filepath.Join(root, CIExpectedFile))
	if err != nil {
		return "", err
	}
	var tagged []test
	var fuzz, short, env []string
	err = filepath.WalkDir(root, func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if d.IsDir() {
			switch d.Name() {
			case ".git", "node_modules", "bin", "site", "worktrees":
				return filepath.SkipDir
			}
			return nil
		}
		if !strings.HasSuffix(path, "_test.go") {
			return nil
		}
		rel, _ := filepath.Rel(root, path)
		rel = filepath.ToSlash(rel)
		fset := token.NewFileSet()
		f, err := parser.ParseFile(fset, path, nil, parser.ParseComments)
		if err != nil {
			return fmt.Errorf("%s: %w", rel, err)
		}
		tag := buildTag(f)
		for _, decl := range f.Decls {
			fn, ok := decl.(*ast.FuncDecl)
			if !ok || fn.Recv != nil || fn.Body == nil {
				continue
			}
			name := fn.Name.Name
			calls, gets, shorts := inspect(fn.Body)
			switch {
			case strings.HasPrefix(name, "Fuzz"):
				fuzz = append(fuzz, fmt.Sprintf("%s (%s)", name, filepath.ToSlash(filepath.Dir(rel))))
			case strings.HasPrefix(name, "Test") && tag != "":
				w := whereOf(tag, calls)
				tagged = append(tagged, test{name: name, file: rel, tag: tag, where: w, inCI: ci[name]})
			case strings.HasPrefix(name, "Test"):
				if shorts {
					short = append(short, fmt.Sprintf("%s (%s)", name, filepath.ToSlash(filepath.Dir(rel))))
				}
				for _, g := range gets {
					if strings.HasPrefix(g, "KEVASO_") {
						env = append(env, fmt.Sprintf("%s: %s (%s)", g, name, filepath.ToSlash(filepath.Dir(rel))))
					}
				}
			}
		}
		return nil
	})
	if err != nil {
		return "", err
	}
	sort.Slice(tagged, func(i, j int) bool {
		if tagged[i].tag != tagged[j].tag {
			return tagged[i].tag < tagged[j].tag
		}
		if tagged[i].file != tagged[j].file {
			return tagged[i].file < tagged[j].file
		}
		return tagged[i].name < tagged[j].name
	})
	sort.Strings(fuzz)
	sort.Strings(short)
	sort.Strings(env)
	known := map[string]bool{}
	for _, t := range tagged {
		known[t.name] = true
	}
	var missing []string
	for n := range ci {
		if !known[n] {
			missing = append(missing, n)
		}
	}
	sort.Strings(missing)

	var b strings.Builder
	b.WriteString("# Where the tests run\n\n")
	b.WriteString("<!-- Generated by `make where` from the test code (test/where). Do not edit: test/where's test fails when this file is stale. -->\n\n")
	b.WriteString("Untagged tests run wherever `go test ./...` does: every developer machine, and CI's `unit` job\n")
	b.WriteString("(`make vet race`). Tests behind a build tag need machines. CI's `tags` job compiles every tag\n")
	b.WriteString("for linux and darwin (`make vet-tags`), so tagged code cannot rot, but compiling is not running.\n\n")
	b.WriteString("## Tagged tests\n\n")
	b.WriteString("| Tag | Where it can run | Tests | Run in CI |\n|---|---|---|---|\n")
	type key struct{ tag, where string }
	counts := map[key][2]int{}
	var keys []key
	for _, t := range tagged {
		k := key{t.tag, t.where}
		c, seen := counts[k]
		if !seen {
			keys = append(keys, k)
		}
		c[0]++
		if t.inCI {
			c[1]++
		}
		counts[k] = c
	}
	for _, k := range keys {
		c := counts[k]
		fmt.Fprintf(&b, "| `%s` | %s | %d | %d |\n", k.tag, k.where, c[0], c[1])
	}
	b.WriteString("\nCI's `e2e` job (ubuntu-latest, KVM, no SSH to itself) runs the tests in `" + CIExpectedFile + "`, and\n")
	b.WriteString("fails when any of them reports SKIP (`hack/skipbudget`). Every other tagged test below skips there.\n")
	if len(missing) > 0 {
		b.WriteString("\n**`" + CIExpectedFile + "` names tests that do not exist:** " + strings.Join(missing, ", ") + "\n")
	}
	cur := ""
	for _, t := range tagged {
		if h := t.tag + "|" + t.file; h != cur {
			if cur == "" || !strings.HasPrefix(cur, t.tag+"|") {
				fmt.Fprintf(&b, "\n### `%s`\n\n| Test | File | Where | CI |\n|---|---|---|---|\n", t.tag)
			}
			cur = h
		}
		ci := "skips"
		if t.inCI {
			ci = "**runs**"
		}
		fmt.Fprintf(&b, "| %s | %s | %s | %s |\n", t.name, t.file, t.where, ci)
	}
	b.WriteString("\n## Fuzzers\n\nEvery push runs each fuzzer's seed corpus (plain `go test`). The nightly workflow fuzzes each one\nfor a minute (`make fuzz`).\n\n")
	for _, f := range fuzz {
		b.WriteString("- " + f + "\n")
	}
	b.WriteString("\n## Tests that shrink under `-short`\n\nCI does not pass `-short`, so these run in full on every push; `make test-short` is the quick local loop.\n\n")
	for _, s := range short {
		b.WriteString("- " + s + "\n")
	}
	b.WriteString("\n## Untagged tests that need something outside the Go toolchain\n\nThe variable gates the test: without it, it skips.\n\n")
	for _, e := range env {
		b.WriteString("- " + e + "\n")
	}
	return b.String(), nil
}

// whereOf says where a tagged test can run, from the helpers its body calls.
func whereOf(tag string, calls map[string]bool) string {
	switch {
	case calls["metal2"]:
		return "two bare-metal machines (test/e2e/METAL.md)"
	case calls["metal"] || calls["metalDriver"]:
		return "one bare-metal machine (test/e2e/METAL.md)"
	case strings.Contains(tag, "metal"):
		return "bare metal (test/e2e/METAL.md)"
	case strings.Contains(tag, "e2e"):
		return "Lima VMs on macOS, or a Linux machine with SSH access to its test machines"
	}
	return "see the file"
}

func buildTag(f *ast.File) string {
	for _, cg := range f.Comments {
		if cg.Pos() > f.Package {
			break
		}
		for _, c := range cg.List {
			if t, ok := strings.CutPrefix(c.Text, "//go:build "); ok {
				t = strings.TrimSpace(t)
				// OS constraints are not machine requirements.
				if strings.Contains(t, "e2e") || strings.Contains(t, "metal") {
					return t
				}
				return ""
			}
		}
	}
	return ""
}

// inspect returns the names called in a body, the string literals passed to os.Getenv, and
// whether it calls testing.Short.
func inspect(body *ast.BlockStmt) (calls map[string]bool, gets []string, short bool) {
	calls = map[string]bool{}
	ast.Inspect(body, func(n ast.Node) bool {
		c, ok := n.(*ast.CallExpr)
		if !ok {
			return true
		}
		switch fn := c.Fun.(type) {
		case *ast.Ident:
			calls[fn.Name] = true
		case *ast.SelectorExpr:
			if x, ok := fn.X.(*ast.Ident); ok {
				switch {
				case x.Name == "testing" && fn.Sel.Name == "Short":
					short = true
				case x.Name == "os" && (fn.Sel.Name == "Getenv" || fn.Sel.Name == "LookupEnv") && len(c.Args) == 1:
					if lit, ok := c.Args[0].(*ast.BasicLit); ok {
						gets = append(gets, strings.Trim(lit.Value, `"`))
					}
				}
			}
		}
		return true
	})
	return calls, gets, short
}

func readList(path string) (map[string]bool, error) {
	f, err := os.Open(path)
	if err != nil {
		return nil, err
	}
	defer func() { _ = f.Close() }() // read-only
	out := map[string]bool{}
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		line := strings.TrimSpace(sc.Text())
		if i := strings.Index(line, "#"); i >= 0 {
			line = strings.TrimSpace(line[:i])
		}
		if line != "" {
			out[line] = true
		}
	}
	return out, sc.Err()
}
